<?php
/**
 * Покрытие английского словаря.
 *
 * Собирает все ключи t('…') с кириллицей из шаблонов, контроллеров, моделей и
 * хелперов и сверяет с app/Lang/en-admin.php. Непереведённая строка не ломает
 * интерфейс (Lang::t тихо падает на русский), поэтому найти пропуск глазами
 * невозможно — только замером.
 *
 * Запуск: php tools/i18n_coverage.php [--list]
 */

declare(strict_types=1);

/* Подписи для админки живут не только в шаблонах: каталог событий webhook и
   права API — в моделях, относительное время — в хелперах. */
$roots = ['templates', 'app/Controllers', 'app/Models', 'app/Core', 'app/Oidc', 'app/Social'];
$files = ['app/helpers.php'];

/** Ключ может быть склеен: t('первая часть ' . 'вторая'). Берём цепочку целиком.
    t_html() — тот же перевод с разметкой в подстановках (v4.74, письма). */
const KEY_RE = '~\bt(?:_html)?\(\s*((?:\'(?:[^\'\\\\]|\\\\.)*\'\s*\.\s*)*\'(?:[^\'\\\\]|\\\\.)*\')~s';
const PART_RE = '~\'((?:[^\'\\\\]|\\\\.)*)\'~';

$keys = [];
$scan = static function (string $path) use (&$keys): void {
    $src = (string)file_get_contents($path);
    preg_match_all(KEY_RE, $src, $m);
    foreach ($m[1] ?? [] as $expr) {
        preg_match_all(PART_RE, $expr, $parts);
        /* В одинарных кавычках PHP снимает ровно два экранирования: \' и \\.
           stripslashes() снимала все подряд и портила ключи с обратным слэшем:
           regex в подсказке про веб-сервер приходил без него и не находился в
           словаре, хотя перевод был на месте. */
        $key = (string)preg_replace('~\\\\([\'\\\\])~', '$1', implode('', $parts[1]));
        /* Точечные ключи вида login.submit живут в основном словаре */
        if (preg_match('~[А-Яа-яЁё]~u', $key)) $keys[$key] = true;
    }
    /* Строки, которые переводятся при выводе (v4.74): тост, заголовок страницы,
       страница ошибки. Контроллеры передают их строкой, раскладка зовёт t().
       До 4.74 не переводились вовсе — и сканер их не видел: английский
       интерфейс показывал «Сохранено» и «Доступ закрыт», а отчёт был зелёным.
       Только литерал целиком: склеенная строка в словаре не найдётся и так.
       Машинные API (Admin API, SCIM, метрики) отвечают JSON, а не интерфейсом. */
    /* Слова склонения (v4.74): не на русском plural() отдаёт t(one) или t(many),
       а при many = one — t(few). Требуем перевод всех трёх: так проще, чем
       повторять здесь правило выбора. До 4.74 английская панель писала
       «5 ключей» — plural() переводом не пользовался, и сторож молчал. */
    if (preg_match_all("~\bplural\((?:[^,()]|\([^()]*\))+,\s*'([^']+)',\s*'([^']+)',\s*'([^']+)'\s*\)~u", $src, $pm)) {
        foreach (array_merge($pm[1], $pm[2], $pm[3]) as $w) $keys[$w] = true;
    }
    if (preg_match('~(Api|Scim|Metrics)Controller\.php$~', $path)) return;
    $lit ='\'((?:[^\'\\\\]|\\\\.)*)\'';
    foreach (["~Flash::(?:success|error|info)\\(\\s*$lit\\s*\\)~", "~'pageTitle'\\s*=>\\s*$lit\\s*[,\\]]~",
              "~ErrorPage::oauth\\(\\s*$lit\\s*(?:,\\s*$lit\\s*)?[,)]~","~'(?:title|message)'\\s*=>\\s*$lit\\s*[,\\]]~"] as $re) {
        if (!preg_match_all($re, $src, $mm)) continue;
        foreach (array_slice($mm, 1) as $group) {
            foreach ($group as $raw) {
                $key = (string)preg_replace('~\\\\([\'\\\\])~', '$1', (string)$raw);
                if (preg_match('~[А-Яа-яЁё]~u', $key)) $keys[$key] = true;
            }
        }
    }
};

foreach ($roots as $dir) {
    if (!is_dir($dir)) continue;
    foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir)) as $f) {
        if (!$f->isFile() || $f->getExtension() !== 'php') continue;
        if (str_contains(str_replace('\\', '/', $f->getPathname()), '/Lang/')) continue;
        $scan($f->getPathname());
    }
}
foreach ($files as $f) if (is_file($f)) $scan($f);

/* Строки из КАТАЛОГОВ. Сканер выше ищет `t('…')` и потому их не видит: они
   лежат данными, а через t() проходят позже — в оболочке разделов
   (`t($current['title'])`), в подписи уровня (`AccessLevel::title`), в сетке
   прав (`t($title)`).

   Слепое пятно было настоящим: пятьдесят одна строка из ста девятнадцати не
   имела перевода, и английский интерфейс показывал русскую колонку разделов в
   каждой карточке — организации, сервиса, человека, здоровья. Проверка при
   этом была зелёной. */
$catalogFiles = array_merge(
    (array)glob('app/Core/*Map.php'),
    ['app/Core/Permission.php', 'app/Core/AccessLevel.php',
     /* Каталог юридических документов: Legal::title() и titleAccusative()
        оборачивают эти строки в t(), а сканер их не видел — и заголовки
        «Политика конфиденциальности», «Пользовательское соглашение» числились
        в отчёте НЕИСПОЛЬЗУЕМЫМИ, хотя стоят на экране регистрации у каждого.
        Перевод у них случайно был; не будь его — проверка бы промолчала. */
     'app/Core/Legal.php',
     /* Каталог писем: подписи кнопок и темы проходят через t() в разделе
        «Письма». «Войти» — кнопка письма со ссылкой для входа — тоже значилась
        неиспользуемой. */
     'app/Core/MailTemplates.php',
     /* Каталог уведомлений владельцу: пара «заголовок, пояснение» на событие.
        Форма та же, что у областей прав, — не хватало только имени файла. */
     'app/Core/AdminNotify.php',
     /* Поля реквизитов оператора данных: подпись, подсказка и placeholder
        собираются в форму циклом, и ни одна из этих строк не встречается в
        коде как t('…'). */
     'app/Core/Requisites.php']
);
$catalogRe = [
    "~'(?:title|desc)'\s*=>\s*'([^']+)'~u",            // разделы карточек
    "~=>\s*\['[a-z_]+',\s*'([^']+)'~u",                 // ступени уровней
    /* Области прав и пары «заголовок, пояснение». `\[\s*` — пара бывает и в
       столбик: оповещение «Мост с порталом проложен» так и числилось
       переведённым, не имея перевода (найдено разбором токенов, v4.74). */
    "~'[a-z_.]+'\s*=>\s*\[\s*'([^']+)',\s*'([^']+)'~u",
    /* Документы: винительный падеж для строки «Принимаю …». */
    "~'acc'\s*=>\s*'([^']+)'~u",
    /* Письма: всё, что человек видит. `when` — пояснение в админке, `token` и
       `vars` — служебные, их сюда не берём. */
    "~'(?:subject|greeting|body|button|when)'\s*=>\s*'([^']+)'~u",
    /* Поля форм, собираемых из каталога: реквизиты оператора данных.
       `key`, `type` и `mask` — служебные, а `placeholder` человек читает. */
    "~'(?:label|hint|placeholder)'\s*=>\s*'([^']+)'~u",
];
/* Словарь событий аудита (v4.70): «событие → по-человечески», одна пара на
   строку. Форма `'ключ' => 'текст'` слишком общая, чтобы искать её во всех
   каталогах, — поэтому правило привязано к одному файлу. До v4.70 словарь жил
   в истории объекта и не проверялся вовсе: английская карточка показывала
   историю по-русски, а отчёт был зелёным. */
$fileRe = [
    /* Подпись события и подпись группы событий для фильтра журнала (v4.71):
       ключ — машинное имя, значение — кириллица. Пар бывает по нескольку в
       строке, поэтому без привязки к началу. */
    'app/Core/Audit.php' => ["~'[a-z0-9_.]+'\s*=>\s*'([А-Яа-яЁё][^']*)'~u"],
    /* Страницы ошибок: код => [заголовок, текст]; переводятся при выводе (v4.74). */
    'app/Core/ErrorPage.php' => ["~\d{3}\s*=>\s*\['([^']+)',\s*'([^']+)'\]~u"],
    /* Тексты писем «как в поставке» (v4.74): переводятся на язык письма, и до
       этого не проверялись вовсе — английское письмо выходило наполовину
       русским, а отчёт был зелёным. */
    'app/Core/MailTemplates.php' => [
        "~'(?:title|when|subject|greeting|body|button)'\s*=>\s*'([А-Яа-яЁё][^']*)'~u",
        "~FOOTER_DEFAULT =\s*'([^']+)'~u",
    ],
    /* Готовые схемы оформления (v4.78): «ключ => ['Имя', [палитра]]», имя
       выводится через t() на плитке редактора. */
    'app/Core/Bridge.php' => ["~'[a-z]+'\s*=>\s*\['([А-Яа-яЁё][^']*)',\s*\[~u"],
    /* Уведомления человеку: «событие => [подпись, включено ли]». Подпись стоит
       в настройках профиля — и до 4.74 выводилась без перевода вовсе. */
    'app/Core/Notify.php' => ["~'[a-z0-9_.]+'\s*=>\s*\[\s*'([^']+)',\s*(?:true|false)~u"],
];
/* Группы разделов в оболочке карточки: `GROUPS = ['setup' => 'Подключение']`,
   выводятся через t(). «Люди и роли» и «Разбор» перевода не имели. */
foreach ((array)glob('app/Core/*Map.php') as $mf) {
    $fileRe[$mf][] = "~'[a-z_]+'\s*=>\s*'([А-Яа-яЁё][^']*)'~u";
}
foreach (array_merge($catalogFiles, array_keys($fileRe)) as $cf) {
    if (!is_file($cf)) continue;
    $src = (string)file_get_contents($cf);
    foreach (array_merge($catalogRe, $fileRe[$cf] ?? []) as $re) {
        if (!preg_match_all($re, $src, $cm)) continue;
        foreach (array_slice($cm, 1) as $group) {
            foreach ($group as $raw) {
                $key = (string)$raw;
                if (preg_match('~[А-Яа-яЁё]~u', $key)) $keys[$key] = true;
            }
        }
    }
}

$en = (array)require __DIR__ . '/../app/Lang/en-admin.php';
$keys = array_keys($keys);
sort($keys, SORT_NATURAL | SORT_FLAG_CASE);

$missing = array_values(array_diff($keys, array_keys($en)));
$unused = array_values(array_diff(array_keys($en), $keys));

printf("ключей в коде: %d\n", count($keys));
printf("переведено:    %d\n", count($keys) - count($missing));
printf("не переведено: %d\n", count($missing));
/* «Не используется» — два очень разных случая, и мерить их одним числом
   значит не мерить ничего.

   Первый: строка удалённого экрана. Ключ лежит балластом, вреда от него нет.
   Второй, важный: строка ЖИВА, просто сканер её не видит — она приходит в t()
   через переменную или собирается циклом из каталога. Такой ключ выглядит
   мусором, а на деле показывает, где проверка слепа: пропади у него перевод —
   интерфейс молча заговорит по-русски, а гейт останется зелёным.

   Отличаем прямым поиском текста по исходникам. Совпадение в комментарии
   ошибку не создаёт: оно лишь оставляет ключ в списке «жив, но не виден», где
   ему и место до тех пор, пока сканер не научится читать этот каталог. */
$hay = '';
foreach (['app', 'templates', 'install', 'public'] as $d) {
    if (!is_dir($d)) continue;
    foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($d)) as $f) {
        $p = str_replace('\\', '/', (string)$f);
        if (!is_file($p) || str_contains($p, '/Lang/')) continue;
        if (!in_array(pathinfo($p, PATHINFO_EXTENSION), ['php', 'js'], true)) continue;
        $hay .= (string)file_get_contents($p) . "\n";
    }
}
$blind = array_values(array_filter($unused, static fn($k) => str_contains($hay, (string)$k)));
$dead = array_values(array_diff($unused, $blind));

printf("в словаре, но не используются: %d\n", count($unused));
printf("  · текст есть в коде — сканер до него не дошёл: %d\n", count($blind));
printf("  · текста в коде нет — ключ мёртвый: %d\n", count($dead));

if (in_array('--list', $argv, true)) {
    foreach ($missing as $m) echo "  НЕТ ПЕРЕВОДА: $m\n";
    foreach ($unused as $u) echo "  НЕ ИСПОЛЬЗУЕТСЯ: $u\n";
}
exit($missing === [] ? 0 : 1);
