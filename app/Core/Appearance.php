<?php

declare(strict_types=1);

namespace App\Core;

use App\Models\Client;

/**
 * Публичное лицо установки: главная и экран входа (v4.8).
 *
 * До этого «оформление» было размазано: снимок панели входа лежал во вкладке
 * «Брендинг» вместе с логотипом и favicon, витрина включалась сама по галочке
 * в карточке КАЖДОГО портала, а состав формы входа не настраивался вовсе —
 * показывалось всё, что вообще умеет система.
 *
 * Разделение простое и по признаку «кто это видит»:
 *
 *  · **Брендинг** — то, что видно везде: имя, акцент, логотип, favicon. Оно
 *    красит и админку, и письма, и профиль.
 *  · **Оформление сайта** (этот класс) — то, что видит НЕ вошедший человек:
 *    главная и форма входа. Единственные две страницы, которые показывают
 *    посторонним, и единственные, на которые смотрят с чужого сайта.
 *
 * Все тумблеры по умолчанию включены: поведение установки, обновлённой с
 * прошлой версии, не меняется ни на пиксель, пока владелец сам чего-нибудь не
 * выключит (§1, опциональность).
 */
final class Appearance
{
    /** Способы входа, которые можно убрать с экрана. */
    public const METHODS = ['password', 'magic', 'passkey', 'social'];

    /**
     * Показывать ли способ входа.
     *
     * Умолчание — «да»: выключенный по умолчанию способ означал бы, что после
     * обновления часть людей не может войти привычным образом и никто об этом
     * не предупредил.
     */
    public static function method(string $name): bool
    {
        return Setting::get('appearance.method_' . $name, '1') !== '0';
    }

    /** Кнопки сервисов — над формой (v4.86), как у Google, Apple и X; по умолчанию — под ней. */
    public static function socialFirst(): bool
    {
        return Setting::get('appearance.social_first', '0') === '1';
    }

    /**
     * Сколько способов входа осталось включено.
     *
     * Нужно не для показа, а для запрета: выключить все — значит запереть всех
     * снаружи, включая себя. Соцвход в счёт не идёт, если ни один провайдер не
     * настроен, — «включено» и «работает» тут разные вещи.
     */
    public static function methodsLeft(): int
    {
        $n = 0;
        foreach (self::METHODS as $m) {
            if (!self::method($m)) continue;
            if ($m === 'social' && \App\Social\Provider::enabled() === []) continue;
            $n++;
        }
        return $n;
    }

    /**
     * Показывать ли витрину проектов на главной.
     *
     * Двойное условие намеренно: тумблер владельца И хотя бы один отмеченный
     * портал. Пустая витрина хуже, чем сразу форма входа, — это лишний экран
     * на пути к тому, зачем человек пришёл.
     */
    public static function showcase(): bool
    {
        return Setting::get('appearance.showcase', '1') !== '0';
    }

    /**
     * Оформление экрана входа — на весь сайт (v4.77): кабинет и панель в тех
     * же цветах, шрифтах и скруглениях.
     *
     * Владелец: «раздел сделан правильно, но только под форму авторизации, а
     * можно распространить на проект глобально». Палитра и так даёт все токены
     * интерфейса с гарантией контраста (приглушённый текст, линии, рамки
     * полей, текст на кнопке), поэтому её можно приложить к любой странице.
     * Выключить — оформление останется только на экранах входа.
     */
    public static function lookEverywhere(): bool
    {
        return Setting::get('appearance.look_everywhere', '1') !== '0';
    }

    /** Чей дизайн главнее на входе в портал с темой из манифеста (v4.85). */
    public const PORTAL_LOOKS = ['portal', 'site', 'only'];

    /**
     * portal — что портал прислал, то его, остальное от сайта (как в 4.82);
     * site — шрифты, форма, карточки, узор, фон и раскладка от сайта, цвета —
     * портала; only — порталы с темой из манифеста выглядят как вход в установку.
     *
     * Владелец 26.09: «почему на формы авторизации порталов не
     * распространяется общий дизайн код, задаваемый /admin/appearance?» — Портфолио
     * присылает манифестом почти всё (палитру, скругление 6, свои шрифты), и
     * от сайта до его входа доходило одно стекло. По умолчанию — site.
     */
    public static function portalLook(): string
    {
        $v = (string)Setting::get('appearance.portal_look', 'site');
        return in_array($v, self::PORTAL_LOOKS, true) ? $v : 'site';
    }

    /** Порталы витрины — те, что отмечены владельцем и включены. */
    public static function showcasePortals(): array
    {
        return self::showcase() ? Client::publicOnes() : [];
    }

}
