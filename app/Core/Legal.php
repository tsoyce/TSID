<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Правовые документы инсталляции и записи о согласии (v3.9).
 *
 * Тексты живут в настройках, а не в файлах: владелец правит их из админки, и они
 * обязаны пережить обновление кода. Настройки уже в БД и уже попадают в бэкап.
 *
 * Ключевое здесь — версия. Каждое сохранение изменённого текста поднимает
 * `version`, а запись о согласии хранит номер версии числом. Без этого запись
 * бессмысленна: документ перепишут, а «согласился» будет указывать на текст,
 * которого человек никогда не видел.
 *
 * ВАЖНО: шаблоны ниже — заготовки, а не юридический документ. Их обязан
 * прочитать и поправить владелец установки; об этом сказано и в самой админке.
 */
final class Legal
{
    /**
     * Реестр документов.
     *
     * consent = требуется галочка при регистрации. У реквизитов её нет: это
     * справка о владельце, соглашаться с ней не с чем.
     */
    public const DOCS = [
        'privacy'    => ['title' => 'Политика конфиденциальности', 'consent' => true,
                         'acc' => 'политику конфиденциальности'],
        'consent'    => ['title' => 'Согласие на обработку персональных данных', 'consent' => true,
                         'acc' => 'согласие на обработку персональных данных'],
        'terms'      => ['title' => 'Пользовательское соглашение', 'consent' => true,
                         'acc' => 'пользовательское соглашение'],
        'requisites' => ['title' => 'Реквизиты владельца', 'consent' => false,
                         'acc' => 'реквизиты владельца'],
    ];

    public static function ready(): bool
    {
        return Migrations::ready('legal_consents');
    }

    public static function title(string $key): string
    {
        return t(self::DOCS[$key]['title'] ?? $key);
    }

    /**
     * Название в винительном падеже — для строки «Принимаю …».
     * Заголовок в именительном давал «Принимаю политика конфиденциальности».
     * В английском форма та же, что и в именительном, — словарь это разрулит.
     */
    public static function titleAccusative(string $key): string
    {
        return t(self::DOCS[$key]['acc'] ?? (self::DOCS[$key]['title'] ?? $key));
    }

    /** Включён ли документ. Пустой текст = выключен: пустая страница хуже отсутствующей. */
    public static function enabled(string $key): bool
    {
        if (!isset(self::DOCS[$key])) return false;
        return Setting::get("docs.$key.enabled") === '1' && trim(self::body($key)) !== '';
    }

    /** Исходный текст (Markdown). Пусто — значит, ещё не заполняли. */
    public static function body(string $key): string
    {
        return (string)Setting::get("docs.$key.body", '');
    }

    public static function version(string $key): int
    {
        return (int)Setting::get("docs.$key.version", '0');
    }

    public static function updatedAt(string $key): ?string
    {
        $v = (string)Setting::get("docs.$key.updated_at", '');
        return $v !== '' ? $v : null;
    }

    /**
     * Готовый HTML с подставленными плейсхолдерами.
     *
     * Первая строка вида «# Название» отбрасывается: заголовок страницы рисует
     * шаблон, и без этого он оказывался бы на странице дважды. Документы почти
     * всегда начинают с собственного заголовка — и шаблоны по умолчанию, и то,
     * что принесёт владелец из своего юриста.
     */
    public static function html(string $key): string
    {
        $body = ltrim(self::fill(self::body($key)));
        $body = (string)preg_replace('~^#\s+[^\n]*\n?~u', '', $body, 1);
        return Markdown::toHtml($body);
    }

    /**
     * Сохранить текст. Версия растёт только когда текст действительно изменился:
     * иначе открыл-закрыл форму — и у всех согласия «протухли».
     */
    public static function save(string $key, string $body, bool $enabled): void
    {
        if (!isset(self::DOCS[$key])) return;
        $body = trim($body);
        $changed = $body !== trim(self::body($key));

        Setting::set("docs.$key.body", $body);
        Setting::set("docs.$key.enabled", $enabled ? '1' : '0');
        if ($changed) {
            Setting::set("docs.$key.version", (string)(self::version($key) + 1));
            Setting::set("docs.$key.updated_at", now());
            Audit::log('legal.updated', ['meta' => ['doc' => $key, 'version' => self::version($key)]]);
        }
    }

    /**
     * Документы, под которыми нужна галочка при регистрации.
     * @return array<string, array{title: string, version: int}>
     */
    public static function requiringConsent(): array
    {
        $out = [];
        foreach (self::DOCS as $key => $def) {
            if (!$def['consent'] || !self::enabled($key)) continue;
            $out[$key] = [
                'title' => self::title($key),
                'acc' => self::titleAccusative($key),
                'version' => self::version($key),
            ];
        }
        return $out;
    }

    /**
     * Записать согласие. Идемпотентно: та же редакция второй раз не пишется,
     * поэтому повторная отправка формы не плодит дубли.
     *
     * @param list<string> $keys
     */
    public static function record(int $userId, array $keys): void
    {
        if (!self::ready()) return;
        foreach ($keys as $key) {
            if (!isset(self::DOCS[$key]) || !self::enabled($key)) continue;
            $version = self::version($key);
            $exists = DB::val('SELECT id FROM {legal_consents}
                WHERE user_id = ? AND doc_key = ? AND doc_version = ?', [$userId, $key, $version]);
            if ($exists !== null) continue;
            DB::insert('legal_consents', [
                'user_id' => $userId,
                'doc_key' => $key,
                'doc_version' => $version,
                'accepted_at' => now(),
                'ip' => ip_bin(),
                'user_agent' => request_ua(),
            ]);
        }
    }

    /** @return list<array> согласия человека — для профиля и выгрузки данных */
    public static function consentsOf(int $userId): array
    {
        if (!self::ready()) return [];
        return DB::all('SELECT * FROM {legal_consents} WHERE user_id = ? ORDER BY accepted_at DESC', [$userId]);
    }

    /**
     * Подставить данные инсталляции. Плейсхолдеры, а не готовый текст, потому
     * что название и домен владелец меняет в брендинге, и переписывать из-за
     * этого три документа руками — гарантированный способ забыть один.
     */
    public static function fill(string $text): string
    {
        /* Реквизиты идут отсюда же и списком: раньше подстановок было четыре, и
           всё остальное — ИНН, адрес, руководитель — владелец вписывал в текст
           КАЖДОГО документа руками. При переезде офиса это четыре правки
           вместо одного поля, и три из них забываются. */
        return strtr($text, Requisites::placeholders() + [
            '{{ Название }}' => Setting::appName(),
            '{{ Домен }}' => (string)parse_url(base_url(), PHP_URL_HOST),
            /* Прежние два имени остаются рабочими: их набирали в текстах
               документов до появления реквизитов, и молча сломать чужой
               документ нельзя. Значение берётся из реквизитов, а старое —
               только если реквизиты пусты. */
            '{{ Владелец }}' => Requisites::get('operator')
                ?: (string)Setting::get('docs.owner', Setting::appName()),
            '{{ Контакт }}' => Requisites::get('email')
                ?: (string)Setting::get('docs.contact', ''),
        ]);
    }

    /** Заготовка документа — то, что подставляется кнопкой «взять шаблон». */
    public static function template(string $key): string
    {
        return match ($key) {
            'privacy' => self::PRIVACY,
            'consent' => self::CONSENT,
            'terms' => self::TERMS,
            'requisites' => self::REQUISITES,
            default => '',
        };
    }

    private const PRIVACY = <<<'MD'
