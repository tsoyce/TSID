        ## Какие данные мы обрабатываем

        - адрес электронной почты — как основной способ входа и восстановления доступа;
        - имя и фамилия, если вы их указали, — для отображения в интерфейсе;
        - номер телефона, пол, дата рождения — если вы их указали или разрешили
          передать сервису, через который входили;
