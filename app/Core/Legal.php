        ## Зачем мы это делаем

        - вход в подключённые сервисы под единой учётной записью;
        - защита аккаунта: уведомления о входах, обнаружение подбора пароля;
        - выполнение требований законодательства.

        ## Кому передаются данные

        Данные передаются подключённым сервисам только в объёме, который вы
        подтвердили при первом входе в конкретный сервис, и только тем сервисам,
        в которые вы входили сами.

