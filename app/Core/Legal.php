        - посмотреть и изменить свои данные в профиле;
        - выгрузить всё, что о вас хранится, одним архивом;
        - удалить учётную запись;
        - отозвать доступ у любого подключённого сервиса.

        ## Контакты

        По вопросам обработки данных: {{ Контакт }}

        Оператор: {{ Владелец }}
        MD;

