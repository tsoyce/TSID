<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Каталог прав (v4.3).
 *
 * Право — строка `область.действие`, ровно как rwx: строки — области,
 * столбцы — чтение, изменение, удаление. Сетка галочек в `/admin/roles`
 * показывает всю раскладку разом; до этого права были зашиты в код тремя
 * ступенями (обычный / admin / superadmin), и «тестировщик, который видит
 * всё, но ничего не меняет» в них не помещался.
 *
 * Каталог — единственный источник правды о том, какие права бывают. Хранить
 * в базе список возможных прав незачем: он меняется вместе с кодом, который
 * их спрашивает, и разъехаться они не должны.
 */
final class Permission
{
    /** Действия — те самые rwx. Порядок важен: он же порядок столбцов. */
    public const ACTIONS = [
        'read' => 'Смотреть',
        'write' => 'Изменять',
        'delete' => 'Удалять',
    ];

    /**
     * Области. Ключ — префикс права, значение — [подпись, пояснение,
     * какие из действий вообще применимы].
     *
     * Не у всякой области есть все три действия: журнал аудита не правят и
     * не удаляют поштучно, а «удалить настройку» не значит ничего. Показывать
     * галочку, которая ничего не включает, — врать интерфейсом.
     */
    /*
     * Четвёртый элемент — почему недостающих действий нет.
     * Причина была написана комментарием в коде и до интерфейса не доезжала, а
     * пустая клетка без объяснения читается как «выключено», то есть как
     * «можно включить». Пусто там, где действия все.
     */
    public const AREAS = [
        'users' => ['Пользователи', 'Карточки людей, блокировка, доступы', ['read', 'write', 'delete'], ''],
        'clients' => ['Порталы', 'Подключение сервисов, реквизиты, карта ролей', ['read', 'write', 'delete'], ''],
        'orgs' => ['Организации', 'Состав и групповые доступы', ['read', 'write', 'delete'], ''],
        'roles' => ['Роли', 'Справочник ролей и эта самая таблица прав', ['read', 'write', 'delete'], ''],
        'logs' => ['Логи и аудит', 'Журнал событий и безопасности', ['read'],
            'Аудит не правят и не удаляют поштучно: смысл журнала в том, что его нельзя подчистить'],
        'settings' => ['Настройки', 'Брендинг, SMTP, политики, документы', ['read', 'write'],
            '«Удалить настройку» не значит ничего: у каждой есть значение по умолчанию'],
    ];

    /**
     * Особые права: они не про «область × действие» и в сетку не ложатся.
     * Отдельным списком, а не втиснутые в матрицу ради красоты.
     */
    public const SPECIAL = [
        'impersonate' => ['Входить от имени', 'Смотреть систему глазами человека. Действия пишутся в аудит от вашего имени'],
        'keys.rotate' => ['Ротация ключей', 'Перевыпуск ключей подписи: порталы обязаны перечитать JWKS'],
        'backup' => ['Бэкап', 'Скачивание архива с ключами и дампом базы'],
        'housekeeping' => ['Чистка', 'Удаление логов, выгрузок и файлов-сирот'],
    ];

    /**
     * Наборы для встроенных ролей.
     *
     * `superadmin` в списке нет намеренно: ему разрешено всё, и держать это
     * галочками значило бы позволить снять их с себя и запереть систему.
     */
    public const DEFAULTS = [
        'admin' => [
            'users.read', 'users.write', 'users.delete',
            'clients.read', 'clients.write',
            'orgs.read', 'orgs.write',
            'roles.read',
            'logs.read',
            'settings.read',
            'impersonate', 'housekeeping',
        ],
        'user' => [],
        /* Делегированный админ портала. `clients.write` ему нужен: он правит
           свой портал, а границу «только свой» держит assertClientScope, а не
           отсутствие права. Без записи он мог бы только смотреть — то есть
           делегированное администрирование перестало бы работать вовсе. */
        'client_admin' => ['users.read', 'clients.read', 'clients.write'],
        /* Организация. Права те же, что у админа портала, плюс состав людей:
           владелец распоряжается своими проектами и своими участниками.
           Границу «только своё» держит область выдачи, а не отсутствие права —
           как и у делегированного админа портала. */
        'org_owner' => ['users.read', 'users.write', 'clients.read', 'clients.write',
                        'orgs.read', 'orgs.write'],
        'org_admin' => ['users.read', 'clients.read', 'clients.write', 'orgs.read'],
    ];

    /** Уровни доступа по умолчанию для встроенных ролей (ACCESS_MODEL.md §1). */
    public const DEFAULT_LEVEL = [
        'superadmin' => 91,
        'admin' => 70,
        'org_owner' => 80,
        'org_admin' => 75,
        'client_admin' => 70,
        'user' => 20,
    ];

    /** Все существующие права одним списком — для проверки ввода. */
    public static function all(): array
    {
        $out = [];
        foreach (self::AREAS as $area => [, , $actions]) {
            foreach ($actions as $a) $out[] = $area . '.' . $a;
        }
        foreach (array_keys(self::SPECIAL) as $p) $out[] = $p;
        return $out;
    }

    public static function exists(string $perm): bool
    {
        return in_array($perm, self::all(), true);
    }

    /** Человеческое название права — для аудита и подсказок. */
    public static function label(string $perm): string
    {
        if (isset(self::SPECIAL[$perm])) return t(self::SPECIAL[$perm][0]);
        [$area, $action] = array_pad(explode('.', $perm, 2), 2, '');
        if (!isset(self::AREAS[$area], self::ACTIONS[$action])) return $perm;
        return t(self::ACTIONS[$action]) . ' · ' . t(self::AREAS[$area][0]);
    }

    /**
     * Право подразумевает чтение своей области.
     *
     * Иначе получается роль, которая «может изменять, но не может смотреть» —
     * набор галочек, из которого нельзя составить работающий экран. Дописываем
     * молча, а не ругаемся: человек хотел разрешить, а не запретить.
     *
     * @param list<string> $perms
     * @return list<string>
     */
    public static function withImplied(array $perms): array
    {
        foreach ($perms as $p) {
            [$area, $action] = array_pad(explode('.', $p, 2), 2, '');
            if ($action !== '' && $action !== 'read' && isset(self::AREAS[$area])) {
                $perms[] = $area . '.read';
            }
        }
        return array_values(array_unique(array_filter($perms, [self::class, 'exists'])));
    }
}
