<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Разметка правовых документов — намеренно маленькое подмножество Markdown.
 *
 * Почему не разрешить HTML. Тексты правит администратор из админки, а
 * администратор — не всегда тот, кому можно доверять произвольный HTML: одна
 * учётка с правами на настройки превращается в XSS на странице, которую видят
 * все посетители. Поэтому вход экранируется целиком, и только потом из
 * экранированного текста собирается разметка. Вставить тег в обход этого
 * невозможно: к моменту сборки «<» уже стал «&lt;».
 *
 * Почему не библиотека. Composer в проде нет (§0 архитектуры), а полноценный
 * парсер ради заголовков и списков — несоразмерно.
 *
 * Поддерживается: заголовки ##/###, списки, нумерованные списки, ссылки,
 * **жирный**, *курсив*, абзацы. Всё остальное остаётся текстом.
 */
final class Markdown
{
    public static function toHtml(string $src): string
    {
        /* Экранируем ДО разбора: дальше в тексте нет ни одного живого тега,
           и любой «<script>» — уже безобидная последовательность символов. */
        /* Нулевой байт вырезается: им помечаются вынутые моноширинные куски
           (см. inline), и пришедший из текста он спутал бы нумерацию. */
        $src = esc(str_replace(["\r\n", "\x00"], ["\n", ''], $src));

        $out = [];
        $list = null;   // 'ul' | 'ol' | null — какой список открыт
        $para = [];

        /* Разметка внутри строки применяется ПОСЛЕ склейки, а не к каждой
           строке отдельно. Иначе выделение, разорванное переносом, не находило
           пары и оставалось на экране звёздочками:

               … уходит **мимо
               настроек уведомлений**: это единственное …

           Текст и документов, и CHANGELOG свёрстан по ширине окна редактора,
           так что перенос посреди выделения — не редкость, а норма. */
        $closePara = static function () use (&$para, &$out): void {
            if ($para === []) return;
            /* Строки абзаца склеиваются пробелом, а не <br>. Одиночный перенос
               в Markdown мягкий, и текст документов свёрстан по ширине окна
               редактора — с <br> он рвался бы посреди предложения ровно там,
               где автор нажал Enter, а не там, где кончается строка у читателя. */
            $out[] = '<p>' . self::inline(implode(' ', $para)) . '</p>';
            $para = [];
        };
        /* Текущий пункт копится сырым по той же причине, что и абзац: пункты
           переносят по ширине окна, и выделение так же разрывается. */
        $li = null;
        $closeLi = static function () use (&$li, &$out): void {
            if ($li === null) return;
            $out[] = '<li>' . self::inline($li) . '</li>';
            $li = null;
        };
        $closeList = static function () use (&$list, &$out, $closeLi): void {
            $closeLi();
            if ($list === null) return;
            $out[] = "</$list>";
            $list = null;
        };

        foreach (explode("\n", $src) as $line) {
            $t = trim($line);

            if ($t === '') { $closePara(); $closeList(); continue; }

            if (preg_match('~^(#{1,4})\s+(.+)$~u', $t, $m)) {
                $closePara(); $closeList();
                /* Заголовок первого уровня — это заголовок страницы, он рисуется
                   шаблоном. Внутри текста начинаем с h2, иначе на странице
                   окажется два h1 и структура развалится. */
                $level = min(4, strlen($m[1]) + 1);
                $out[] = "<h$level>" . self::inline($m[2]) . "</h$level>";
                continue;
            }

            if (preg_match('~^[-*]\s+(.+)$~u', $t, $m)) {
                $closePara(); $closeLi();
                if ($list !== 'ul') { $closeList(); $out[] = '<ul>'; $list = 'ul'; }
                $li = $m[1];
                continue;
            }

            if (preg_match('~^\d+[.)]\s+(.+)$~u', $t, $m)) {
                $closePara(); $closeLi();
                if ($list !== 'ol') { $closeList(); $out[] = '<ol>'; $list = 'ol'; }
                $li = $m[1];
                continue;
            }

            /* Продолжение пункта списка. Длинный пункт переносят на следующую
               строку — и в наших заготовках, и в любом тексте, который принесёт
               владелец. Без этого продолжение закрывало список и становилось
               отдельным абзацем: пункт разрывался пополам. */
            if ($li !== null) {
                $li .= ' ' . $t;
                continue;
            }

            $closeList();
            $para[] = $t;
        }
        $closePara();
        $closeList();

        return implode("\n", $out);
    }

    /** Внутристрочное: ссылки, жирный, курсив, моноширинный. */
    private static function inline(string $s): string
    {
        /* Моноширинные куски вынимаются ПЕРВЫМИ и на их место встают метки.
           Внутри обратных кавычек показывают саму разметку — звёздочки, скобки,
           подчёркивания, — и пока этот текст лежал в строке, он участвовал в
           разборе наравне с остальным. Выделение вокруг такого куска не
           складывалось вовсе: в `**Заглушка слала сообщение на `*`**` жирное
           начало искало пару, натыкалось на одинокую звёздочку в кавычках и
           сдавалось, оставляя две звезды на экране. Метка звёздочек не
           содержит, поэтому дальше разбор идёт по чистому тексту. */
        $code = [];
        $s = (string)preg_replace_callback('~`([^`]+)`~u', static function (array $m) use (&$code): string {
            $code[] = $m[1];
            return "\x00" . (count($code) - 1) . "\x00";
        }, $s);

        /* Ссылка. Схема проверяется явно: «javascript:» в href — тот же XSS,
           только с другой стороны, и экранирование от него не спасает. */
        $s = (string)preg_replace_callback(
            '~\[([^\]]+)\]\(([^)\s]+)\)~u',
            static function (array $m): string {
                $href = $m[2];
                $safe = preg_match('~^(https?://|mailto:|/)~i', $href) === 1;
                if (!$safe) return $m[1];   // подозрительная ссылка — остаётся текстом
                /* Внешние ссылки уводят с сайта: rel обязателен, иначе открытая
                   страница получает доступ к window.opener. v5.4: «//host» —
                   тоже внешняя (схема от страницы), и HTTP://… — тоже. */
                $ext = preg_match('~^(https?:)?//~i', $href) === 1;
                return '<a href="' . $href . '"'
                    . ($ext ? ' target="_blank" rel="noopener noreferrer"' : '') . '>' . $m[1] . '</a>';
            },
            $s
        );

        $s = (string)preg_replace('~\*\*([^*]+)\*\*~u', '<strong>$1</strong>', $s);
        $s = (string)preg_replace('~(?<!\*)\*([^*]+)\*(?!\*)~u', '<em>$1</em>', $s);

        return (string)preg_replace_callback('~\x00(\d+)\x00~', static function (array $m) use ($code): string {
            return '<code>' . ($code[(int)$m[1]] ?? '') . '</code>';
        }, $s);
    }
}
