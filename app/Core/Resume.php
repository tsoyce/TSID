<?php

declare(strict_types=1);

namespace App\Core;

use App\Models\OneTimeToken;

/**
 * Возврат на портал, не зависящий от сессии (v4.38).
 *
 * Обещание SSO ровно одно: пришёл с сайта А — вернёшься на сайт А. Держалось
 * оно на `$_SESSION['oauth_request']`, то есть на том, что PHP-сессия доживёт
 * от `/authorize` до отправки формы входа. Обычно доживает. Но сессия — вещь
 * хрупкая: её роняет и чужая настройка cookie, и вход, открытый во второй
 * вкладке, и сборщик мусора при долгой возне с паролем. А когда она падает,
 * человек оказывается в личном кабинете SSO — там, куда он не собирался, — и
 * выглядит это как «SSO меня съело».
 *
 * Поэтому запрос авторизации кладётся ещё и в базу, а его ключ едет в адресе и
 * в скрытом поле формы. Сессия остаётся первым источником — она быстрее, — а
 * ключ подстраховывает.
 *
 * Ключ живёт полчаса — дольше вход не длится — и при использовании не гасится
 * (v4.60): повторное нажатие «Войти» или «Продолжить» обязано вернуть туда же,
 * а не в личный кабинет. До 4.60 ключ был одноразовым, и именно это уводило в
 * кабинет человека, нажавшего второй раз. Не защищала одноразовость ничего:
 * первое использование ключа так же сильно, как второе. Сам по себе ключ ничего
 * не открывает — нужно войти, код уйдёт только на зарегистрированный адрес
 * портала и привязан к его PKCE, — а сколько он живёт, ограничивает срок.
 */
final class Resume
{
    public const TYPE = 'authorize_resume';

    /** Запомнить запрос авторизации, вернуть ключ для адреса. */
    public static function issue(array $query): string
    {
        try {
            return OneTimeToken::issue(null, self::TYPE, ['q' => $query]);
        } catch (\Throwable $e) {
            /* Не смогли — не беда: сессия по-прежнему первый источник, и без
               подстраховки всё работает ровно как раньше. */
            Log::warning('resume_issue_failed', ['err' => $e->getMessage()]);
            return '';
        }
    }

    /**
     * Привести запрос к виду, пригодному для адреса.
     *
     * Только строки: в адрес всё равно поедут строки, а массив в
     * http_build_query развернулся бы в `a[0]=…` и сломал бы запрос.
     *
     * @return array<string,string>|null
     */
    private static function clean(mixed $q): ?array
    {
        if (!is_array($q) || empty($q['client_id']) || empty($q['redirect_uri'])) return null;
        $out = [];
        foreach ($q as $k => $v) {
            if (is_string($k) && (is_string($v) || is_int($v))) $out[$k] = (string)$v;
        }
        return $out;
    }

    /**
     * Запрос по ключу — не гася его.
     *
     * ОДНО И ТО ЖЕ нажатие может прийти дважды: кнопка возвращается через
     * пятнадцать секунд, или возврат оборвался, и человек жмёт снова. Запрос из
     * сессии к этому времени съеден первым нажатием, и возврат держит только
     * ключ. Погасить его — значит оставить повтор ни с чем (см. описание класса).
     *
     * @return array<string,string>|null
     */
    public static function peek(string $token): ?array
    {
        $token = trim($token);
        if ($token === '') return null;
        try {
            $row = OneTimeToken::peek($token, self::TYPE);
        } catch (\Throwable) {
            return null;
        }
        return self::clean($row['payload']['q'] ?? null);
    }


    /** Ключ из текущего запроса: форма важнее адреса — она свежее. */
    public static function fromRequest(): string
    {
        $rt = (string)($_POST['rt'] ?? $_GET['rt'] ?? '');
        return preg_match('~^[A-Za-z0-9_-]{16,128}$~', $rt) === 1 ? $rt : '';
    }

    /** Скрытое поле для форм входа, регистрации и второго фактора. */
    public static function field(): string
    {
        $rt = self::fromRequest();
        return $rt === '' ? '' : '<input type="hidden" name="rt" value="' . esc($rt) . '">';
    }
}
