<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Номер аккаунта: девять цифр, которые человек может продиктовать (v3.8).
 *
 * Зачем он нужен, если у аккаунта уже есть `sub`. Sub — это UUID: он стабилен,
 * уникален и живёт в базах порталов, но продиктовать его в поддержку нельзя, и
 * узнать себя в нём человек тоже не может. Номер решает ровно эту задачу и
 * ничего больше: он не заменяет sub и не участвует в протоколе как
 * идентификатор субъекта.
 *
 * Почему случайный, а не по порядку. Последовательный публичный номер выдаёт
 * наружу три вещи разом: сколько всего пользователей, в каком порядке они
 * пришли и с какой скоростью прибывают. Два номера, полученные в разное время,
 * измеряют прирост базы. Случайный не говорит ни о чём.
 *
 * Почему с контрольной цифрой. Номер будут диктовать голосом и набирать руками.
 * Луновская контрольная цифра ловит любую одиночную ошибку и почти все
 * перестановки соседних цифр, так что «не тот аккаунт» отсекается до запроса
 * в базу, а не после.
 *
 * Ёмкость: первая цифра 1–9, дальше семь любых, девятая контрольная — девяносто
 * миллионов номеров. Для самостоятельной установки этого с запасом, а формат
 * остаётся коротким.
 */
final class AccountNumber
{
    /** Всего цифр в номере, включая контрольную. */
    public const LENGTH = 9;

    /** Сгенерировать номер. Уникальность проверяет вызывающий — см. User::assignNumber(). */
    public static function generate(): string
    {
        /* Первая цифра не ноль: иначе номер, где-нибудь потерявший ведущий
           ноль, превращается в восьмизначный и перестаёт совпадать сам с собой. */
        $body = (string)random_int(1, 9);
        for ($i = 0; $i < self::LENGTH - 2; $i++) {
            $body .= (string)random_int(0, 9);
        }
        return $body . self::checkDigit($body);
    }

    /**
     * Подсказать номер по человеку: устойчивая часть от sub, уровень — в первой цифре.
     *
     * Случайный номер ничем не плох, но и ничего не говорит. Здесь первая
     * цифра несёт уровень доступа (9 — владелец, 1 — обычный человек), а
     * остальное выводится из `sub` — то есть у одного и того же человека
     * подсказка всегда одна и та же, сколько ни нажимай.
     *
     * Это ПОДСКАЗКА, а не правило: уровень в номере ничего не разрешает и
     * ничего не запрещает. Проверять права по первой цифре нельзя — номер
     * меняется руками, а роль живёт в таблице ролей. Ноль первой цифрой не
     * бывает: номер, потерявший ведущий ноль, перестаёт совпадать сам с собой.
     */
    public static function suggest(string $sub, int $level): string
    {
        $first = max(1, min(9, (int)round($level / 11.2) ?: 1));
        $seed = substr(hash('sha256', $sub), 0, 16);
        $digits = (string)preg_replace('~\D+~', '', (string)base_convert($seed, 16, 10));
        $body = (string)$first . substr(str_pad($digits, self::LENGTH, '7'), 0, self::LENGTH - 2);
        return $body . self::checkDigit($body);
    }

    /** Цела ли строка: девять цифр и сходится контрольная. */
    public static function isValid(string $number): bool
    {
        $n = self::digits($number);
        if (strlen($n) !== self::LENGTH) return false;
        if ($n[0] === '0') return false;
        return self::checkDigit(substr($n, 0, -1)) === substr($n, -1);
    }

    /**
     * Привести пользовательский ввод к каноническому виду или вернуть null.
     *
     * Принимает «4827-13905», «4827 13905», «482713905» — люди копируют номер
     * вместе с дефисом и пробелами, и отказывать им из-за этого незачем.
     */
    public static function normalize(string $input): ?string
    {
        $n = self::digits($input);
        return self::isValid($n) ? $n : null;
    }

    /** Для показа: 482713905 → 4827-13905. Группы разной длины — так труднее сбиться. */
    public static function format(string $number): string
    {
        $n = self::digits($number);
        if (strlen($n) !== self::LENGTH) return $number;
        return substr($n, 0, 4) . '-' . substr($n, 4);
    }

    /**
     * Контрольная цифра по Луну (ISO/IEC 7812-1) для строки из цифр.
     *
     * Публичная: её считает и форма ввода в браузере, показывая последнюю
     * клетку сразу, — но решает всё равно сервер. Расхождение двух реализаций
     * стоит дорого, поэтому здесь она эталонная, а браузерная лишь показывает.
     */
    public static function checkDigit(string $body): string
    {
        $sum = 0;
        /* Удваивается каждая вторая цифра, считая справа от будущей
           контрольной, — то есть последняя цифра тела и через одну. */
        $double = true;
        for ($i = strlen($body) - 1; $i >= 0; $i--) {
            $d = (int)$body[$i];
            if ($double) {
                $d *= 2;
                if ($d > 9) $d -= 9;
            }
            $sum += $d;
            $double = !$double;
        }
        return (string)((10 - $sum % 10) % 10);
    }

    private static function digits(string $s): string
    {
        return (string)preg_replace('~\D~', '', $s);
    }
}
