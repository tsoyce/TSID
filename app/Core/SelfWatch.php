<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Сторож собственных адресов SSO: discovery, ключи подписи, экран входа.
 *
 * Зачем он, если есть «Прозвон». Прозвон отвечает, когда его спрашивают, а
 * спрашивают его, когда что-то уже сломалось и кто-то уже пожаловался.
 *
 * На хостинге с панелью (BrainyCP и подобные) конфиг веб-сервера принадлежит
 * панели, а не нам. Правку, которая пропускает /.well-known до приложения,
 * панель может молча перезаписать своим шаблоном — при продлении сертификата
 * или смене настроек сайта. Код панели закодирован, починить шаблон на её
 * стороне нельзя. Остаётся одно: узнать о поломке в тот же час, а не от
 * портала, который перестал подключаться.
 *
 * Пишет владельцу, когда состояние СМЕНИЛОСЬ с «отвечает» на «сломано». Каждый
 * час об одном и том же не пишет: письмо, которое приходит каждый час, перестают
 * читать, и в день настоящей поломки его тоже не прочтут. Починилось — молча
 * возвращается в «отвечает» и снова ждёт.
 *
 * Молчание (код 0) тревогой не считается: из cron на этом же сервере публичный
 * адрес может не резолвиться сам в себя, и сторож поднимал бы ложную тревогу
 * там, где снаружи всё работает.
 */
final class SelfWatch
{
    /** Последнее известное состояние: ok | bad. */
    private const STATE = 'health.self_state';

    public static function run(): string
    {
        $bad = [];
        $answered = 0;
        foreach (Probe::self() as $r) {
            if ((int)($r['code'] ?? 0) === 0) continue;
            $answered++;
            if (in_array($r['status'] ?? '', ['warn', 'fail'], true)) {
                $bad[] = $r['name'] . ' — ' . $r['note'];
            }
        }
        if ($answered === 0) return 'снаружи не достучаться — состояние не меняем';

        $was = (string)Setting::get(self::STATE, 'ok');
        $now = $bad === [] ? 'ok' : 'bad';
        Setting::set(self::STATE, $now);

        if (self::transition($was, $now) === 'broken') {
            AdminNotify::say('health.self',
                fn() => t('SSO перестал отвечать по стандартным адресам. Чаще всего это панель хостинга перезаписала конфиг веб-сервера — например, вернула правило, которое отдаёт /.well-known с диска.')
                . "\n\n" . implode("\n", $bad),
                fn() => [t('Адрес') => rtrim(base_url(), '/'), t('Когда') => fmt_dt(now())]);
        }
        return $now === 'ok' ? 'всё отвечает' : 'сломано: ' . count($bad);
    }

    /**
     * Смена состояния — отдельно от сети, чтобы решение о письме было проверяемо.
     *
     * @return 'broken'|'recovered'|null
     */
    public static function transition(string $was, string $now): ?string
    {
        if ($was !== 'bad' && $now === 'bad') return 'broken';
        if ($was === 'bad' && $now === 'ok') return 'recovered';
        return null;
    }
}
