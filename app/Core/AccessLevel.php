<?php

declare(strict_types=1);

namespace App\Core;

use App\Models\Role;

/**
 * Уровень доступа — сводка для СЕРВИСОВ (v4.3). Разбор — ACCESS_MODEL.md.
 *
 * Одно число 0–99, по которому портал ветвится, не изучая словарь наших ролей.
 * Считается по ролям человека; направление одно — роли → уровень, обратного
 * пересчёта нет и не будет, иначе появится второй источник правды.
 *
 * Внутри SSO уровень прав не даёт: здесь решают права (App\Core\Permission).
 * Иначе в одной системе оказалось бы два механизма авторизации, и однажды они
 * ответили бы по-разному на один и тот же вопрос.
 */
final class AccessLevel
{
    /**
     * Ступени: порог → машинное имя и подпись. Промежутки оставлены намеренно —
     * новая ступень между 20 и 50 не сломает уже написанные на той стороне
     * сравнения `>= 50`.
     */
    public const TIERS = [
        0 => ['blocked', 'Заблокирован'],
        1 => ['archived', 'Архивный'],
        10 => ['guest', 'Гость'],
        20 => ['user', 'Пользователь'],
        25 => ['trusted', 'Доверенный'],
        50 => ['observer', 'Наблюдатель'],
        55 => ['moderator', 'Модератор'],
        60 => ['editor', 'Редактор'],
        65 => ['publisher', 'Выпускающий'],
        70 => ['service_admin', 'Администратор сервиса'],
        75 => ['people_admin', 'Администратор с управлением людьми'],
        80 => ['org_admin', 'Администратор организации'],
        90 => ['sso_observer', 'Наблюдатель SSO'],
        91 => ['superadmin', 'Суперадмин'],
        98 => ['superadmin_limited', 'Суперадмин без системного раздела'],
        99 => ['owner', 'Владелец инсталляции'],
    ];

    /**
     * Уровень пользователя во всей установке — наибольший из имеющихся.
     *
     * Статус старше роли: заблокированный получает 0, какие бы роли ему ни
     * оставили. Владелец получает 99 не из роли, а из владения инсталляцией —
     * роль тут ни при чём.
     *
     * ЭТО НЕ ТО, ЧТО ЕДЕТ В ТОКЕН. Порталу нужен уровень человека У НЕГО, и
     * для этого есть forClient(). Здесь — «кто этот человек в системе»: такой
     * ответ уместен в админке и на удостоверении, но не в чужом сервисе.
     */
    public static function of(array $user): int
    {
        return self::forClient($user, null);
    }

    /**
     * Уровень пользователя в конкретном портале.
     *
     * Считается по ролям, которые к этому порталу относятся: глобальные (они
     * действуют везде) плюс роли самого портала. Роли ЧУЖИХ порталов не
     * учитываются — и это весь смысл метода.
     *
     * До v4.22.1 уровень считался один на всю установку, и человек, которого
     * сделали админом одного сервиса, приезжал администратором во все
     * остальные: список ролей в токене фильтровался по порталу, а число —
     * нет. Портал, читающий `access_level >= 70` (как учит его наша же
     * integration.md), открывал ему админку.
     *
     * @param int|null $clientDbId null — «во всей установке», для админки
     */
    public static function forClient(array $user, ?int $clientDbId): int
    {
        $id = (int)($user['id'] ?? 0);
        if ($id === 0) return 0;
        $status = (string)($user['status'] ?? '');
        if ($status === 'blocked') return 0;
        if ($status === 'deleted') return 1;

        /* Пол — уровень базовой роли `user`: живой человек не бывает нулём.
           Ноль на нашей шкале означает «заблокирован», и отдавать его тому,
           у кого просто нет ролей в этом портале, значит сказать порталу
           неправду — тем более что в claim `roles` мы `user` дописываем
           всегда. Оба утверждения обязаны сходиться. */
        $level = max(Role::levelOfUser($id, $clientDbId), Role::baseLevel());
        if (Owner::id() === $id) $level = max($level, 99);
        return max(0, min(99, $level));
    }

    /** Машинное имя ступени: ближайшая снизу. */
    public static function tier(int $level): string
    {
        return self::tierRow($level)[0];
    }

    /** Подпись ступени для интерфейса. */
    public static function title(int $level): string
    {
        return t(self::tierRow($level)[1]);
    }

    /** @return array{0: string, 1: string} */
    private static function tierRow(int $level): array
    {
        $best = self::TIERS[0];
        foreach (self::TIERS as $threshold => $row) {
            if ($level >= $threshold) $best = $row;
        }
        return $best;
    }
}
