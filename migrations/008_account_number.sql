-- SSO · 008_account_number — человекочитаемый номер аккаунта (v3.8).
--
-- У аккаунта уже есть sub (UUID): он стабилен, уникален и лежит в базах
-- порталов. Но продиктовать его в поддержку нельзя, и узнать себя в нём человек
-- тоже не может. Номер закрывает ровно это и в протоколе субъекта не заменяет.
--
-- Колонка nullable, а не NOT NULL: значения выдаёт приложение (случайные, с
-- контрольной цифрой по Луну — средствами SQL такое не сгенерировать, тем более
-- переносимо между MySQL и SQLite). Существующие аккаунты заполняет PHP-шаг
-- 008_account_number.php, который выполняется сразу после этого файла.
--
-- Уникальность — отдельным индексом, а не в ALTER TABLE: SQLite не умеет
-- добавлять колонку с UNIQUE, а CREATE UNIQUE INDEX понимают оба движка.
-- NULL под уникальным индексом повторяться разрешено и там, и там, поэтому
-- индекс можно ставить до заполнения.

ALTER TABLE {users} ADD COLUMN account_number CHAR(9) NULL;
CREATE UNIQUE INDEX uq_users_account_number ON {users} (account_number);
