-- SSO · 022_org_scope — организация владеет проектами (v4.25).
--
-- Фаза 3 работ по SCOPES.md. Убирает вторую систему полномочий.
--
-- Что было: `org_members.role` — перечисление ENUM('owner','admin','member'),
-- зашитое в схему. У него нет ни прав из {role_permissions}, ни уровня
-- доступа, ни какой-либо связи с таблицей {roles}. То есть «роль в
-- организации» и «роль» означали разное, и сложить их было нельзя: человек,
-- назначенный владельцем организации, в системе прав оставался никем.
--
-- Что стало: полномочия организации — обычные роли (`org_owner`, `org_admin`),
-- выданные с областью `org:X`. Такая выдача покрывает все проекты
-- организации — то самое наследование, ради которого заводились области.
--
-- Колонка `org_members.role` остаётся на месте, но больше не читается: она
-- превращается в след истории. Сносить её пришлось бы пересборкой таблицы на
-- SQLite, а выигрыш — один столбец; уберётся заодно с другой пересборкой.
--
-- Само членство остаётся строкой в {org_members}: «состоит в организации» —
-- самостоятельный факт, не совпадающий с «имеет в ней полномочия». Именно им
-- организация выдаёт доступ к порталам целиком (org_client_access).

-- Вся работа — в PHP-шаге: она читает состав и заводит выдачи, а такое
-- одинаково на MySQL и SQLite не пишется.
