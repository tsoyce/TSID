-- Быстрая переавторизация (v4.20): PIN как запасной путь к отпечатку.
--
-- Хэш, а не код: PIN короткий, и хранить его обратимо нельзя тем более. Argon2id
-- на четырёх цифрах бессмысленен против того, у кого есть база, — но у того, у
-- кого есть база, и так есть всё. Защита здесь от другого: от чужих рук на
-- разблокированном устройстве.
--
-- Столбец на пользователе, а не на сессии: PIN один на человека, а запирается
-- каждая его сессия отдельно.
ALTER TABLE {users} ADD COLUMN pin_hash VARCHAR(255) NULL;

-- Когда сессию заперли. NULL — не заперта.
-- На сессии, а не в PHP-сессии: замок обязан пережить закрытие вкладки, иначе
-- он защищает ровно от того, кто и так ушёл.
ALTER TABLE {sessions} ADD COLUMN locked_at DATETIME NULL;
