<?php

declare(strict_types=1);

/**
 * PHP-шаг миграции 008: раздать номера уже существующим аккаунтам.
 *
 * SQL этого не может: номер случайный и с контрольной цифрой. Шаг идемпотентен —
 * трогает только строки, где номер ещё не проставлен, — потому что выполняется
 * до записи версии в {migrations}, и при сбое следом миграцию запустят заново.
 *
 * Порядок выдачи намеренно перемешан относительно id: если раздавать номера
 * подряд по возрастанию id, случайность выродится в порядок регистрации,
 * который номер как раз и не должен выдавать.
 */

return static function (): void {
    $ids = array_column(
        \App\Core\DB::all('SELECT id FROM {users} WHERE account_number IS NULL'),
        'id'
    );
    if ($ids === []) return;
    shuffle($ids);
    foreach ($ids as $id) {
        \App\Models\User::assignNumber((int)$id);
    }
};
