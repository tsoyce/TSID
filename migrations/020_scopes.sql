-- SSO · 020_scopes — области доступа: система → организация → сервис (v4.23).
--
-- Проект целиком — в SCOPES.md. Здесь только схема, и только первая фаза:
-- колонки появляются и заполняются по тому, что уже есть, но ничего ещё не
-- начинает работать по-новому. Так сделано намеренно — чтобы новый механизм
-- сначала доказал на проверках, что считает ровно то же самое, что старый.
--
-- Область — пара (тип, идентификатор): system | org:N | client:N. Одно
-- отношение между областями — покрытие: system ⊇ org:X ⊇ client:C (если C
-- принадлежит X). Из него выводятся роли, права и уровень доступа.

-- ── Проект принадлежит организации ────────────────────────────────────────
-- NULL — ничей, то есть системного уровня. Владение (эта колонка) и допуск
-- ({org_client_access}) — разные отношения: первое отвечает «чей проект»,
-- второе «кого туда пускают». До сих пор было только второе, и фразу
-- «у организации X есть проекты А и Б» выразить было нечем.
ALTER TABLE {clients} ADD COLUMN org_id BIGINT UNSIGNED NULL;
CREATE INDEX ix_clients_org ON {clients} (org_id);

-- ── Дом роли: где она определена ──────────────────────────────────────────
-- Не путать с областью выдачи ниже. Роль «Админ портала» определена один раз
-- на уровне системы, а выдаётся сколько угодно раз с областью конкретного
-- портала. Разделение этих двух понятий и убирает главную беду сегодняшней
-- схемы: строку роли на каждый подключённый сервис.
--
-- client_id пока остаётся: он и есть источник для расстановки (PHP-шаг рядом),
-- и страховка на случай, если фазу придётся откатить. Уйдёт в фазе 2.
ALTER TABLE {roles} ADD COLUMN scope_type VARCHAR(16) NOT NULL DEFAULT 'system';
ALTER TABLE {roles} ADD COLUMN scope_id BIGINT UNSIGNED NULL;

-- ── Область выдачи: где роль действует ────────────────────────────────────
-- Ключ таблицы (user_id, role_id) пока не трогаем: сейчас одна роль выдаётся
-- человеку один раз, и расширять ключ незачем. Он станет
-- (user_id, role_id, scope_type, scope_id) в фазе 2 — там появится системная
-- роль «Админ портала», выданная одному человеку сразу на несколько порталов,
-- и без расширенного ключа вторая выдача не ляжет. Отдельной фазой потому,
-- что SQLite меняет первичный ключ только пересборкой таблицы.
ALTER TABLE {user_roles} ADD COLUMN scope_type VARCHAR(16) NOT NULL DEFAULT 'system';
ALTER TABLE {user_roles} ADD COLUMN scope_id BIGINT UNSIGNED NULL;
CREATE INDEX ix_ur_scope ON {user_roles} (user_id, scope_type, scope_id);

