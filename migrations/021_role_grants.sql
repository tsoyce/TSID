-- SSO · 021_role_grants — одна роль вместо копии на каждый портал (v4.24).
--
-- Фаза 2 работ по SCOPES.md. Первая, которая меняет данные, а не только схему.
--
-- Что было: `Role::ensureClientAdmin()` заводил строку роли «Админ портала» на
-- КАЖДЫЙ подключённый сервис. Три роли по смыслу превращались в `3 + N` строк
-- по факту, и все они попадали в один плоский список в карточке человека. Сто
-- сервисов — сто три пункта, из которых сто раз написано одно и то же.
--
-- Что стало: одна системная роль «Админ портала», выданная с областью
-- конкретного портала. Роль определена в одном месте, выдана во многих — это и
-- есть разделение, ради которого заводились области (SCOPES §2.1).
--
-- Вся работа — в PHP-шаге рядом: она требует чтения данных и переноса выдач,
-- а такое одинаково на MySQL и SQLite не пишется. Здесь остаётся только то,
-- что выражается схемой.

-- Ключ выдачи расширяется до (user_id, role_id, scope_type, scope_id).
-- Без этого один человек не может быть админом двух порталов: пара
-- (user_id, role_id) у него теперь одна и та же, различает их только область.
-- Пересборка — в PHP-шаге: SQLite меняет первичный ключ лишь пересозданием
-- таблицы, а MySQL — своим синтаксисом.
