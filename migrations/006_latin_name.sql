-- SSO · 006_latin_name — латинское написание имени задаётся человеком (v3.4).
--
-- Зачем: автоматическая транслитерация не может знать, как имя написано в
-- документах конкретного человека. Правил несколько — ИКАО Doc 9303, ГОСТ
-- 7.79, старая французская школа, — и они дают разный результат: «Артём Петров»
-- по ИКАО превращается в ARTEM TSOI, а в паспорте у человека может стоять
-- ARTYOM PETROV. Угадывать тут нечего, поэтому поля заполняет владелец аккаунта,
-- а транслитерация остаётся лишь подсказкой по умолчанию.
--
-- Пустое значение = «считай автоматически», поэтому NULL, а не пустая строка.

-- Без AFTER: SQLite такого не понимает, а порядок колонок ни на что не влияет.
ALTER TABLE {users} ADD COLUMN latin_first_name VARCHAR(100) NULL;
ALTER TABLE {users} ADD COLUMN latin_last_name VARCHAR(100) NULL;
