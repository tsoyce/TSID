-- SSO · 025_portal_theme — экран входа в оформлении портала (v4.65).
--
-- Портал присылает в манифесте не только цвет, логотип и подпись, но и тему:
-- фон, карточку, текст, акценты обеих тем, скругление, шрифты из нашего списка
-- и цитату для левой панели. Всё — параметрами: CSS, HTML и скрипты от портала
-- по-прежнему не принимаются (см. App\Core\Bridge).
--
-- Одной колонкой JSON, а не десятком скаляров: тема читается целиком на каждом
-- показе экрана входа и целиком же проверяется — применять её по частям нельзя,
-- контраст считается для набора цветов, а не для каждого отдельно. В колонке
-- лежит только прошедшее проверку полей; пригодность темы целиком (контраст)
-- считается при показе, чтобы правка правил не требовала перезаписи данных.

ALTER TABLE {clients} ADD COLUMN brand_theme JSON NULL;
