-- SSO · 015_audit_object — измерение «организация» в журнале (v4.4).
--
-- Журнал умел отвечать на вопрос «что было с этим объектом» только для двух
-- сущностей из трёх: у события есть on_user_id и client_id, а организации в
-- нём нет вовсе — её слаг лежал внутри JSON-поля meta.
--
-- Доставать оттуда можно было бы запросом по JSON, но синтаксис у MySQL и
-- SQLite разный, а значит проверка в разработке (SQLite) ничего не сказала бы
-- о боевой (MySQL). Ровно так уже ломалась миграция 014. Поэтому измерение
-- становится колонкой: вопрос «история этого объекта» первоклассный, и журнал
-- должен отвечать на него столбцом, а не раскопками.
--
-- client_id существовал, но без индекса: выборка «события этого портала» шла
-- полным сканом журнала, а он растёт быстрее всех таблиц системы.

ALTER TABLE {audit_log} ADD COLUMN org_id BIGINT UNSIGNED NULL;

-- Пара (объект, время) — читаем всегда в этом порядке: последние события
-- конкретного объекта. Индекс только по объекту заставлял бы сортировать.
CREATE INDEX {audit_log}_ix_org ON {audit_log} (org_id, created_at);
CREATE INDEX {audit_log}_ix_client ON {audit_log} (client_id, created_at);
