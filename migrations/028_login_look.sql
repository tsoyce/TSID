-- SSO · 028_login_look — экран входа портала настраивается здесь (v4.71).
--
-- До этого оформление входа приходило только манифестом портала: чтобы вход в
-- Портфолио выглядело как Портфолио, Портфолио прописывало тему в своём JSON. Теперь у портала есть
-- раздел «Экран входа», и оформление задаёт администратор SSO.
--
--   look_mode      откуда брать оформление: portal — как прислал портал (оно же
--                  NULL, умолчание), custom — заданное здесь, off — родной вид
--                  установки без оформления портала;
--   look_theme     своё оформление — тот же набор параметров, что в манифесте,
--                  плюс раскладка, подпись и обложка. Только параметры: CSS
--                  собирает SSO, как и для манифеста;
--   login_methods  способы входа на экране этого портала через запятую. NULL —
--                  как на всём сайте.
--
-- VARCHAR, а не ENUM: см. 024_no_enum — список вариантов живёт в коде.

ALTER TABLE {clients} ADD COLUMN look_mode VARCHAR(8) NULL;
ALTER TABLE {clients} ADD COLUMN look_theme JSON NULL;
ALTER TABLE {clients} ADD COLUMN login_methods VARCHAR(64) NULL;
