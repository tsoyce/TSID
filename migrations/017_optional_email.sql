-- SSO · 017_optional_email — почта перестаёт быть обязательной (v4.5).
--
-- Вопрос пришёл с той стороны, где систему собираются применять: у портала,
-- который подключают, уже есть живые люди, и заводились они логином и паролём.
-- Почты у части из них нет вовсе — не «не указана», а не существует: сервис её
-- никогда не спрашивал, потому что поднимать почтовый сервер ради регистрации
-- дороже, чем обойтись без неё.
--
-- Пока `email NOT NULL`, такого человека в базу не положить. Не «неудобно», а
-- нельзя: перенос упирается в схему на первой же строке. Отсюда и порядок форм
-- на входе — логин с паролем впереди, ссылка на почту следом.
--
-- Что это значит и чего стоит — в §13.2 архитектуры. Коротко: человек без
-- почты входит логином и паролём, но не может восстановить доступ сам, не
-- получает писем безопасности, и порталу в scope email не уходит ничего.
-- Поэтому почта остаётся ожидаемым случаем, а не обязательным.
--
-- Шаг только PHP: MySQL меняет колонку одной строкой, а SQLite не умеет
-- ALTER COLUMN вовсе — там таблицу пересобирают. Один диалект в .sql не
-- ложится, поэтому вся работа в 017_optional_email.php.
