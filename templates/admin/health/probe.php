      '<a class="btn btn-primary" href="/admin/health/probe?run=1">' . esc(t('Прозвонить')) . '</a>') ?>
  <p class="hint mt-8"><?= esc(t('Это настоящие запросы: к своим адресам и к порталам. Поэтому по кнопке, а не при каждом открытии страницы — иначе мы стучались бы к чужим сайтам всякий раз, когда кто-то сюда заглянул.')) ?></p>
<?php else: ?>
<div class="bento-card">
  <div class="bc-title"><?= esc(t('Свои адреса')) ?></div>
  <?= $list($self, t('Нечего звонить.')) ?>
  <?php /* Discovery — единственная проверка, чинить которую надо не в коде, и
           потому единственная, к которой прилагается совет. */ ?>
  <p class="hint mt-8"><?= esc(t('Если discovery не отдаётся, а отвечало не приложение — дело в правиле веб-сервера вида «резать всё, что начинается с точки» (RedirectMatch 404 /\..*$ и подобные). Путь /.well-known/ должен доходить до приложения; на панельном хостинге это правило снимает поддержка.')) ?></p>
</div>

<div class="bento-card mt-16">
