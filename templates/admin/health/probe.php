<?php /**
 * Прозвон: живые запросы туда, куда за нами ходят.
 *
 * «Настроено» и «работает» — разное. Discovery на месте в маршрутах и режется
 * веб-сервером; портал подключён и не отвечает на события. Ни одно из этого не
 * видно по настройкам, и оба случая уже были.
 */
$list = static function (array $rows, string $empty): string {
    if ($rows === []) return '<p class="muted">' . esc($empty) . '</p>';
    $out = '';
    foreach ($rows as $r) {
        /* Разметка та же, что у «Хозяйства»: строка здоровья в проекте одна,
           и заводить ей второй вид ради соседнего раздела незачем. */
        $out .= '<div class="health-row">'
            . '<span class="health-icon">' . status_icon($r['status']) . '</span>'
            . '<div><div class="cell-main">' . esc($r['name']) . '</div>'
            . '<div class="hint">' . esc($r['note']) . ' · ' . esc(t(':n мс', ['n' => (int)$r['ms']])) . '</div></div></div>';
    }
    return $out;
};
?>
