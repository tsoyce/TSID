<?php /**
 * Первый вход в сервис (§5.1): куда человек попал и на что соглашается.
 *
 * Экран один на два случая. Недоверенному порталу он показывает перечень
 * данных — это требование OAuth и здравого смысла. Доверенному не показывает
 * ничего лишнего, но всё равно спрашивает: «доверенный» означает, что мы
 * доверяем сервису данные, а не что человека можно не спрашивать. До v4.19
 * доверенный портал заводил аккаунт молча, и человек оказывался внутри
 * незнакомого сервиса, не поняв, куда пришёл.
 *
 * Это один из самых часто показываемых экранов продукта. До v4.4.7 он был не
 * переведён вовсе: покрытие показывало 100%, потому что считало только строки,
 * уже прошедшие через t(), а эти шли мимо неё.
 */
$scopeHuman = [
    'openid' => t('Идентификатор вашей учётной записи'),
    'profile' => t('Имя, фамилия, аватар, дата рождения'),
    'email' => t('Адрес электронной почты'),
    'phone' => t('Номер телефона'),
    'roles' => t('Ваши роли в этом сервисе'),
    'offline_access' => t('Доступ без вашего присутствия (обновление данных в фоне)'),
];
$trusted = (bool)($client['is_trusted'] ?? false);
$docs = \App\Core\Legal::requiringConsent();
$app = \App\Core\Setting::appName();
?>
<?php /* Заголовок экрана — он же контекст: вкладок здесь нет, и «Вход в
         такой-то» и есть имя страницы. До v4.47 у согласия не было ни
         одного заголовка вовсе — самый показываемый экран продукта
         представлялся программе чтения безымянным. */ ?>
<?= auth_context($client, t('Вход в')) ?>

<?php /* Первая фраза отвечает на «куда я попал». Раньше она начиналась словами
         «Это сервис SSO» — но портал не сервис SSO, он работает ЧЕРЕЗ него,
         и человек читал это как «я ушёл не туда». */ ?>
<p class="muted">
  <?= esc(t('«:portal» работает через :app. Вы войдёте под своей учётной записью — заводить ещё одну не нужно.',
      ['portal' => (string)$client['name'], 'app' => $app])) ?>
</p>

<?php if (!$trusted): ?>
<p class="hint mb-8"><?= esc(t('Сервис получит:')) ?></p>
<ul class="check-list mb-8">
<?php foreach ($scopes as $s): if (!isset($scopeHuman[$s])) continue; ?>
  <li><?= icon('check', 15, 'icon-ok') ?> <?= esc($scopeHuman[$s]) ?></li>
<?php endforeach; ?>
</ul>
<?php /* Строка о пароле — только здесь, под перечнем, к которому она и
         относится. Раньше она стояла внизу экрана всегда, в том числе у
         доверенного портала, где перечня нет: «только перечисленные данные» —
         а перечислено ничего не было, и фраза читалась как загадка. */ ?>
<p class="hint mb-16"><?= esc(t('Больше ничего: пароль остаётся у :app и сервису не передаётся.', ['app' => $app])) ?></p>
<?php endif; ?>

<form method="post" action="/consent" class="stack">
  <?= csrf_field() ?><?= App\Core\Resume::field() ?>
  <?php /* Галочка — только когда есть что принимать (v4.70). Документы
           установки требуют отметки: пассивная строка «продолжая, вы
           соглашаетесь» согласием с ними не является. А без документов
           галочка «я хочу пользоваться этим сервисом» повторяла кнопку
           «Продолжить» — лишний щелчок на самом частом экране продукта.
           Так же устроена регистрация: выключены документы — блока нет.
           Отметка у доступа ставится нажатием «Продолжить» в обоих случаях.

           Документы — каждый своей строкой. Через запятую в одну строку
           «политику конфиденциальности, согласие на обработку персональных
           данных» читались как один документ с длинным названием. */ ?>
  <?php if ($docs !== []): ?>
  <label class="checkbox mb-8">
    <input type="checkbox" name="agree" value="1" required>
    <span><?= esc(t('Я хочу пользоваться этим сервисом')) ?> <?= esc(t('и принимаю:')) ?>
      <span class="consent-docs"><?php foreach ($docs as $key => $doc): ?><a href="/legal/<?= esc($key) ?>" target="_blank" rel="noopener"><?= esc(mb_strtolower($doc['acc'] ?: $doc['title'])) ?></a><?php endforeach; ?></span></span>
  </label>
  <?php endif; ?>
  <button class="btn btn-primary btn-block" name="decision" value="allow" type="submit"><?= esc(t('Продолжить')) ?></button>
  <button class="btn btn-secondary btn-block" name="decision" value="deny" type="submit"><?= esc(t('Не сейчас')) ?></button>
</form>
